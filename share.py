"""Write the model card into the model folder."""

import json

CARD = """---
language: en
license: mit
pipeline_tag: text-classification
base_model: distilbert/distilbert-base-uncased
tags:
  - text-classification
  - distilbert
---

# Lakeshore Bike Share Ticket Router

A fine-tuned DistilBERT model that sorts Lakeshore Bike Share support
messages into four queues: billing, bike_fault, station, and account.

## Intended use

The model reads a short customer support message and predicts which of
the four queues it belongs to, so the message can be routed to the right
team. It is a routing aid for a support lead, not a replacement for a
person reading the message.

## Training data

The training text was invented for this lab. Messages were generated by
a Python script (tickets_data.py) that combines sentence templates for
each queue with Toronto place names, and adds noise: about 12 percent of
messages are vague, about 10 percent mix two topics, and about 8 percent
contain a typing slip. The model was trained on 720 messages, validated
on 240, and tested on 240, from one stratified split. Forty additional
messages were written separately and used only once, at the end, to check
the model on new wording.

## Results

On the held-out test set of 240 messages, the model reached an accuracy
of {test_acc:.3f} and a macro F1 of {test_f1:.3f}. For comparison, a
TF-IDF and logistic regression baseline reached {tfidf_acc:.3f}
accuracy, and always predicting the most common queue reached
{most_acc:.3f}. On the 40 separately written messages, accuracy was
{own_acc:.3f}.

## Limitations

The training text was invented, not collected from real customers, so
the model has only ever seen template-based wording plus the 40 check
messages. Real customer messages will use different words, slang, and
complaints this data never contained, and performance on them will
likely be lower. About 12 percent of the training messages are vague
and cannot be assigned to a queue from their text at all, which puts a
ceiling on accuracy. The model works on English text only and was
fine-tuned from distilbert-base-uncased. It should not be used to make
decisions about a customer without a person reviewing the message.
"""


def main():
    with open("reports/final.json") as handle:
        final = json.load(handle)
    card = CARD.format(
        test_acc=final["test"]["full"]["accuracy"],
        test_f1=final["test"]["full"]["macro_f1"],
        tfidf_acc=final["test"]["tfidf"]["accuracy"],
        most_acc=final["test"]["most_common"]["accuracy"],
        own_acc=final["own_messages_accuracy"],
    )
    with open("model/README.md", "w") as handle:
        handle.write(card)
    print("wrote model/README.md")


if __name__ == "__main__":
    main()
